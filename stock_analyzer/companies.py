def about(ticker: str, yahoo_summary: str | None = None, max_chars: int = 320) -> tuple[str, bool]:
    """(description, is_german). Falls back to the start of Yahoo's English summary."""
    if ticker in ABOUT:
        return ABOUT[ticker], True
    if yahoo_summary:
        text = yahoo_summary.strip()
        if len(text) > max_chars:
            end = text.rfind(". ", 0, max_chars)
            text = text[:end + 1] if end > 80 else text[:max_chars].rsplit(" ", 1)[0] + " …"
        return text, False
    return "", False
